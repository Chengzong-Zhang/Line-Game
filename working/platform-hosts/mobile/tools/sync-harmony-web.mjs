import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(mobileRoot, 'dist');
const resourcesRoot = path.join(mobileRoot, 'harmony/entry/src/main/resources/rawfile');
const generatedWebRoot = path.join(resourcesRoot, 'web');
const marker = path.join(generatedWebRoot, '.lifeline-generated-assets');
const generatedEtsRoot = path.join(mobileRoot, 'harmony/entry/src/main/ets/generated');
const generatedManifest = path.join(generatedEtsRoot, 'AssetManifest.ets');
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
const mimeType = (name) => ({
  '.avif': 'image/avif', '.css': 'text/css', '.f32': 'application/octet-stream',
  '.gif': 'image/gif', '.html': 'text/html', '.ico': 'image/x-icon', '.jpeg': 'image/jpeg',
  '.jpg': 'image/jpeg', '.js': 'application/javascript', '.json': 'application/json',
  '.md': 'text/markdown', '.mjs': 'application/javascript', '.mp3': 'audio/mpeg',
  '.mp4': 'video/mp4', '.pdf': 'application/pdf', '.png': 'image/png', '.svg': 'image/svg+xml',
  '.tex': 'text/plain', '.txt': 'text/plain', '.wasm': 'application/wasm', '.webp': 'image/webp',
  '.woff': 'font/woff', '.woff2': 'font/woff2', '.xml': 'application/xml',
}[path.extname(name).toLowerCase()] ?? 'application/octet-stream');
const safeRoot = path.resolve(resourcesRoot);
if (!path.resolve(generatedWebRoot).startsWith(`${safeRoot}${path.sep}`)) throw new Error('Refusing to write outside Harmony rawfile resources.');
try {
  await readFile(marker);
  await rm(generatedWebRoot, { recursive: true, force: true });
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
  try {
    await readdir(generatedWebRoot);
    throw new Error('Refusing to replace an unmarked Harmony rawfile/web directory.');
  } catch (readError) {
    if (readError?.code !== 'ENOENT') throw readError;
  }
}
await mkdir(generatedWebRoot, { recursive: true });
const entries = [];
const walk = async (folder, prefix = '') => {
  for (const entry of await readdir(path.join(folder, prefix), { withFileTypes: true })) {
    const relative = path.posix.join(prefix.replaceAll('\\', '/'), entry.name);
    if (entry.isDirectory()) await walk(folder, relative);
    else {
      if (relative === '.lifeline-generated-assets') continue;
      const source = path.join(folder, relative);
      const target = path.join(generatedWebRoot, relative);
      await mkdir(path.dirname(target), { recursive: true });
      await cp(source, target);
      entries.push({ path: relative, rawfile: `web/${relative}`, mime: mimeType(relative), sha256: digest(await readFile(source)) });
    }
  }
};
await walk(dist);
entries.sort((a, b) => a.path.localeCompare(b.path, 'en'));
await writeFile(marker, 'generated by mobile/tools/sync-harmony-web.mjs; do not edit\n');
await mkdir(generatedEtsRoot, { recursive: true });
await writeFile(generatedManifest, `// Generated by mobile/tools/sync-harmony-web.mjs.\nexport const PACKAGED_WEB_FILES: string[] = ${JSON.stringify(entries.map(({ path: name }) => name), null, 2)};\n`);
console.log(JSON.stringify({ status: 'PASS-CURRENT', files: entries.length }));
