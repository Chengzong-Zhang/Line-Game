import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs/promises';

const root = path.resolve(process.argv[2] ?? '');
assert.ok(process.argv[2], 'Pass the isolated desktop candidate root.');
const { _electron } = createRequire(path.join(root, 'package.json'))('playwright-core');
const testRoot = path.join(root, 'local_artifacts', `campaign-ui-${Date.now()}`);
await fs.mkdir(testRoot, { recursive: true });
const env = { ...process.env, LIFELINE_TEST_USER_DATA: path.join(testRoot, 'profile') };
delete env.ELECTRON_RUN_AS_NODE;
const application = await _electron.launch({ executablePath: path.join(root, 'desktop/release/win-unpacked/LIFELINE.exe'), env, timeout: 60000 });
try {
  const page = await application.firstWindow();
  const errors = [], network = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/^https?:/i.test(request.url())) network.push(request.url()); });
  page.on('websocket', socket => network.push(socket.url()));
  await page.waitForFunction(() => document.querySelector('#app')?._vnode?.component?.proxy?.controller?.engine);
  const savedQueue = JSON.stringify({ policy: 'anonymous-replay-training-v3', enabled: true, queue: [{ marker: 'preserve-existing' }] });
  await page.evaluate(value => localStorage.setItem('lifeline-training-contribution-v1', value), savedQueue);
  await page.evaluate(() => {
    localStorage.setItem('triaxis-auth', JSON.stringify({ username: 'synthetic', token: 'synthetic' }));
    localStorage.setItem('triaxis-online-session', JSON.stringify({ url: 'wss://example.invalid/ws', roomId: 'ABCD', playerId: 'synthetic', color: 'BLACK' }));
  });
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#app')?._vnode?.component?.proxy?.controller?.engine);
  await page.waitForTimeout(1500);
  assert.deepEqual(network, [], 'an old online session must not reconnect in the offline host');
  assert.equal(await page.evaluate(() => localStorage.getItem('lifeline-training-contribution-v1')), savedQueue, 'opening offline must preserve consent and pending queue bytes');
  assert.equal(await page.evaluate(() => document.querySelector('#app')._vnode.component.proxy.contributionState.enabled), false, 'offline host must not capture contributions');
  await page.evaluate(() => { localStorage.removeItem('triaxis-auth'); localStorage.removeItem('triaxis-online-session'); });
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#app')?._vnode?.component?.proxy?.controller?.engine);
  const skip = page.getByRole('button', { name: '跳过教学', exact: true });
  if (await skip.isVisible()) await skip.click();
  await page.evaluate(async () => {
    const vm = document.querySelector('#app')._vnode.component.proxy;
    vm.selectedTurnTimerEnabled = true;
    await globalThis.Vue.nextTick();
    await vm.startLocalMatch();
  });
  await page.waitForFunction(() => document.querySelector('#app')._vnode.component.proxy.turnTimerPhase === 'running');
  const beforeTimer = await page.evaluate(() => document.querySelector('#app')._vnode.component.proxy.turnTimerRemaining);
  const previousMatch = await page.evaluate(() => JSON.stringify(document.querySelector('#app')._vnode.component.proxy.controller.engine.getSnapshot()));
  await page.getByRole('button', { name: '挑战关卡', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '挑战关卡' });
  assert.equal(await page.evaluate(() => document.querySelector('#app')._vnode.component.proxy.turnTimerPhase), 'paused', 'challenge must pause the live turn timer');
  await page.waitForTimeout(1200);
  await dialog.getByRole('button', { name: '汇成生命枢纽', exact: true }).click();
  await dialog.locator('circle[aria-label="0,2"]').click();
  await dialog.getByText('多条前线已经汇入同一枢纽。', { exact: true }).waitFor();
  const firstAchievement = await page.evaluate(async () => (await globalThis.lifelineDesktop.readAchievements()).achievements.find(item => item.id === 'challenge-first'));
  assert.equal(firstAchievement?.unlocked, true, 'completing a challenge unlocks the host achievement');
  await dialog.getByRole('button', { name: '关卡列表', exact: true }).click();
  assert.ok(await dialog.getByRole('button', { name: '✓ 汇成生命枢纽', exact: true }).isVisible(), 'completion appears in saved profile');
  const backupFile = path.join(testRoot, 'progress.json');
  await application.evaluate(({ dialog }, file) => {
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: file });
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] });
  }, backupFile);
  await dialog.getByRole('button', { name: '导出进度', exact: true }).click();
  await dialog.getByText('备份操作完成。', { exact: true }).waitFor();
  const backup = JSON.parse(await fs.readFile(backupFile, 'utf8'));
  assert.ok(backup.payload.completedChallenges.includes('C01-hub-connection'), 'export must include completed level');
  await page.evaluate(() => {
    const profile = JSON.parse(globalThis.lifelineDesktop.readProfileSync().value);
    profile.progress.completedChallenges = [];
    const result = globalThis.lifelineDesktop.writeProfileSync(JSON.stringify(profile));
    if (!result.ok) throw new Error('Could not prepare the synthetic restore case.');
  });
  await dialog.getByRole('button', { name: '导入进度', exact: true }).click();
  await page.waitForFunction(() => JSON.parse(globalThis.lifelineDesktop.readProfileSync().value).progress.completedChallenges.includes('C01-hub-connection'));
  await dialog.getByText('备份操作完成。', { exact: true }).waitFor();
  assert.ok(await dialog.getByRole('button', { name: '✓ 汇成生命枢纽', exact: true }).isVisible(), 'import must restore the completed level');
  await dialog.getByText('桌面设置', { exact: true }).click();
  await dialog.getByLabel('启用音效').uncheck();
  await dialog.getByLabel('减少动态效果').check();
  await dialog.getByLabel('界面缩放').selectOption('1.1');
  const savedPreferences = await page.evaluate(() => JSON.parse(globalThis.lifelineDesktop.readProfileSync().value).preferences);
  assert.equal(savedPreferences.audioEnabled, false);
  assert.equal(savedPreferences.reducedMotion, true);
  assert.equal(savedPreferences.uiScale, 1.1);
  await dialog.getByRole('button', { name: '返回对局', exact: true }).click();
  assert.equal(await dialog.count(), 0);
  const afterTimer = await page.evaluate(() => ({ phase: document.querySelector('#app')._vnode.component.proxy.turnTimerPhase, remaining: document.querySelector('#app')._vnode.component.proxy.turnTimerRemaining }));
  assert.equal(afterTimer.phase, 'running');
  assert.ok(afterTimer.remaining <= beforeTimer && afterTimer.remaining >= beforeTimer - 2, 'turn timer must resume from its remaining time');
  assert.equal(await page.evaluate(() => JSON.stringify(document.querySelector('#app')._vnode.component.proxy.controller.engine.getSnapshot())), previousMatch, 'challenge must leave the previous match unchanged');
  const persisted = await page.evaluate(() => globalThis.lifelineDesktop.readProfileSync());
  assert.ok(persisted.ok && JSON.parse(persisted.value).progress.completedChallenges.includes('C01-hub-connection'), 'completion must be present in the host profile');
  assert.deepEqual(errors, [], `page errors: ${errors.join('; ')}`);
  assert.deepEqual(network, [], 'offline challenge must not request external services');
  console.log(JSON.stringify({ status: 'PASS_PACKAGED_DESKTOP_CAMPAIGN', savedQueuePreserved: true, firstChallengeCompleted: true, exportAndImport: true, noExternalRequests: true, evidence: testRoot }));
} finally { await application.close(); }
