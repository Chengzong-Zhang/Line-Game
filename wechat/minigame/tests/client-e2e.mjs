import assert from 'node:assert/strict';
import { until } from './helpers.mjs';
import { device } from './transport-device.mjs';

const origin = process.argv[2];
assert.match(origin, /^http:\/\/127\.0\.0\.1:\d+$/);
const blue = device(origin, 'blue'), red = device(origin, 'red'); let restarted;
try {
  assert.equal(await blue.client.enter('create', 7), true);
  const code = blue.client.room.code;
  assert.equal(await red.client.enter('join', code), true);
  await until(() => blue.client.connected && red.client.connected);
  await blue.client.command('ready'); await red.client.command('ready');
  await until(() => blue.client.canPlay());
  assert.equal(red.client.canPlay(), false);
  const original = blue.client.game.stateHash;
  const bad = { ...blue.client.room, revision: blue.client.room.revision + 1, stateHash: 'sha256:' + '0'.repeat(64) };
  assert.equal(await blue.client.receive(bad), false);
  assert.equal(blue.client.game.stateHash, original, 'bad snapshot must not replace original');
  await blue.client.refresh(); assert.equal(blue.client.canPlay(), true);
  blue.faults.dropMessages = true; blue.faults.dropReply = true;
  assert.equal(await blue.client.act({ type: 'move', point: [1, 0] }), false);
  assert.ok(blue.client.pending, 'lost acknowledgement remains recoverable');
  await until(() => red.client.room.seq === 1 && red.client.canPlay());
  blue.stop();
  restarted = device(origin, 'blue', blue.storage);
  await restarted.client.enter('resume', code);
  await until(() => restarted.client.connected && !restarted.client.pending);
  assert.equal(restarted.client.room.seq, 1, 'recovery must not duplicate the move');
  assert.equal(restarted.client.game.stateHash, red.client.game.stateHash);
  assert.equal(await red.client.act({ type: 'skip' }), true);
  await until(() => restarted.client.room.seq === 2 && restarted.client.canPlay());
  assert.equal(await restarted.client.act({ type: 'resign' }), true);
  await until(() => red.client.room.status === 'finished');
  assert.equal(red.client.game.snapshot.winner, 'WHITE');
  await red.client.game.replay(0);
  assert.equal(red.client.game.replayIndex, 0);
  red.client.game.replayInterval = 5;
  assert.equal(red.client.game.startReplayPlayback(), true);
  await until(() => !red.client.game.replayPlaying && red.client.game.replayIndex === red.client.room.seq);
  const inspected = await red.client.game.inspectReplay();
  assert.equal(inspected.stateHash, red.client.room.stateHash); assert.equal(inspected.effects.gameEnded, true);
  await red.client.game.exitReplay(); assert.equal(red.client.game.stateHash, red.client.room.stateHash);
  await red.client.game.replay(0); red.client.game.startReplayPlayback();
  await red.client.command('rematch'); await restarted.client.command('rematch');
  await until(() => red.client.room.seq === 0 && red.client.room.status === 'waiting');
  assert.equal(red.client.game.replayIndex, null); assert.equal(red.client.game.replayView, null);
  assert.equal(red.client.game.replayPlaying, false); assert.equal(red.client.game.replayTimer, null);
  await new Promise(resolve => setTimeout(resolve, 25));
  assert.equal(red.client.game.actions.length, 0);
  assert.deepEqual(red.client.game.snapshot.territories.BLACK.area, 0);
  assert.equal(await red.client.command('leave'), true);
  await until(() => restarted.client.room.status === 'closed');
  const oldToken = red.client.token, localKey = 'lifeline-wechat-session-v1-0';
  red.storage.set(localKey, 'test-only local save sentinel');
  assert.equal(await red.client.deleteAccount(), true);
  assert.equal(red.storage.get(localKey), 'test-only local save sentinel');
  await until(() => restarted.client.error === 'ROOM_REMOVED');
  assert.equal(restarted.client.active, false); assert.equal(restarted.client.reconnectTimer, null);
  assert.equal(red.client.savedCode, null); assert.equal(red.client.token, null);
  await assert.rejects(red.client.platform.request({ url: 'https://test.invalid/api/wechat/rooms', method: 'POST',
    header: { Authorization: `Bearer ${oldToken}`, 'Content-Type': 'application/json' }, data: { gridSize: 7 } }), /ACCOUNT_DELETED/);
  await red.client.enter('create', 7);
  const subject = token => JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString()).sub;
  assert.notEqual(subject(red.client.token), subject(oldToken));
  assert.equal(red.client.room.seq, 0);
  console.log(JSON.stringify({ status: 'PASS_LOCAL_HTTP_WS_ONLY', scope: ['two clients', 'readiness', 'same-source rules', 'mismatch isolation', 'lost acknowledgement', 'restart recovery', 'pass', 'resign', 'replay playback and step inspection', 'rematch cancels replay timers', 'rematch', 'room closure', 'account deletion', 'token revocation', 'local save preserved', 'other client stops reconnecting', 'explicit new identity'] }));
} finally { blue.stop(); red.stop(); restarted?.stop(); }
