export function errorText(code, t) {
  if (!code) return '';
  if (/^MODEL/.test(code)) return t.modelFailure;
  if (code === 'INVALID_CONTROLLERS') return t.invalidPlayers;
  if (code === 'INVALID_PLAY_OPTIONS' || code === 'INVALID_PLAY_PROGRESS') return t.error;
  if (code === 'HINT_DISABLED') return t.hintDisabled;
  if (code === 'HINT_LIMIT') return t.hintLimit;
  if (/REPLAY_|JSON|INVALID_SETTINGS/.test(code)) return t.replayInvalid;
  if (code === 'LIBRARY_FULL') return t.libraryFull;
  if (code === 'LIBRARY_DAMAGED') return t.libraryDamaged;
  if (code === 'CLIPBOARD_UNAVAILABLE') return t.clipboardError;
  if (code === 'TWO_PLAYER_AI_ONLY') return t.twoPlayerAI;
  if (code === 'SAVE_WRITE_FAILED') return t.saveError;
  if (code === 'ONLINE_NOT_CONFIGURED') return t.onlineOff;
  if (code === 'RECONNECTING') return t.reconnecting;
  if (code === 'OTHER_DEVICE') return t.otherDevice;
  if (code === 'ACCOUNT_DELETED') return t.accountDeleted;
  if (code === 'ROOM_REMOVED') return t.roomMissing;
  if (/STATE_MISMATCH|INVALID_ROOM/.test(code)) return t.stateMismatch;
  if (/ROOM_NOT_FOUND|ROOM_CLOSED|ROOM_EXPIRED/.test(code)) return t.roomMissing;
  if (code === 'ROOM_FULL') return t.roomFull;
  if (code === 'ALREADY_IN_ROOM') return t.alreadyInRoom;
  if (/TIMEOUT|WORKER|CANCELLED|^STALE_AI$|^STALE_HINT$/.test(code)) return t.computeRetry;
  if (/STALE_/.test(code)) return t.stalePosition;
  if (/NETWORK|HTTP_|LOGIN|UNAUTHORIZED|BUSY|UNAVAILABLE|TOO_MANY/.test(code)) return t.onlineError;
  if (/INVALID_MOVE|SUPERKO|INVALID_POINT/.test(code)) return t.invalid;
  if (code === 'FOLLOW_HIGHLIGHT') return t.tutorialTarget;
  if (code === 'RECOVERED_BACKUP') return t.recovered;
  if (/SAVE/.test(code)) return t.corrupt;
  return t.error;
}
