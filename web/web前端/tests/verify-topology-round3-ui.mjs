import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import '../TopologyGameEngine.js';
import { compileBoard } from '../BoardCompiler.js';
const noop = () => {};
globalThis.localStorage = { getItem: () => null, setItem: noop, removeItem: noop };
globalThis.location = new URL('http://localhost:8876/');
globalThis.document = { body: { classList: { add: noop, remove: noop, toggle: noop } } };
globalThis.addEventListener = noop;
globalThis.removeEventListener = noop;
globalThis.Vue = { ref: value => ({ value }), shallowRef: value => ({ value }), computed: read => ({ get value() { return read(); } }), watch: noop, nextTick: async () => {}, onMounted: noop, onBeforeUnmount: noop };
globalThis.Worker = class { postMessage() {} terminate() {} };
const { default: App } = await import('../OnlineApp.js');
const setup = App.components.SetupPanel.template;
const slotAt = setup.indexOf('<slot name="topology">');
const sizeAt = setup.indexOf('id="grid-size"');
const startsAt = setup.indexOf('<StartingPointSetup', sizeAt);
const playerAt = setup.indexOf('<LocalPlayerSetup');
const shapeAt = setup.indexOf('id="board-shape"');
assert.ok(playerAt >= 0 && playerAt < sizeAt && sizeAt < shapeAt && shapeAt < slotAt && slotAt < startsAt, 'players, size, shape and topology editor follow the intended order');
assert.match(App.template, /<SetupPanel[\s\S]*?<template #topology>\s*<TopologySetupPanel v-if="selectedBoardShape === 'custom'"[\s\S]*?<\/template>\s*<\/SetupPanel>/);
assert.match(setup, /\['triangle', 'hexagon', 'custom'\]/);
const panel = App.components.TopologySetupPanel;
const panelState = panel.setup({ language: 'en', draft: {} });
assert.deepEqual(panelState.presetNames, ['cylinder', 'mobius', 'torus', 'klein-bottle', 'tetrahedron', 'cone', 'sphere']);
assert.match(panel.template, /topology-preset-effective-size/);
assert.match(panel.template, /gridSize % 2 === 0/);
assert.doesNotMatch(panel.template, /网格需要偶数条边段/);
assert.equal((panel.template.match(/<details class="local-player-advanced" open>/g) || []).length, 0);
const css = await readFile(new URL('../styles.css', import.meta.url), 'utf8');
assert.doesNotMatch(css, /\.utility-grid-board\s*>\s*\.topology-setup[^}]*grid-row/);
const app = App.setup();
app.tutorialActive.value = false;
app.handleBoardShapeChange('custom');
for (const name of ['cone', 'sphere']) {
  for (let size = 5; size <= 15; size++) {
    app.handleGridSizeChange(size);
    const result = app.selectTopologyPreset(name);
    assert.ok(result, `${name}/${size}: ${app.topologySetupMessage.value}`);
    assert.equal(app.selectedTopologyDefinition.value.topology.preset, name);
    assert.ok(compileBoard(app.selectedTopologyDefinition.value).ok);
    const next = size === 15 ? 14 : size + 1;
    app.handleGridSizeChange(next);
    assert.equal(app.selectedTopologyDefinition.value.topology.preset, name, 'resizing retains chosen preset');
    assert.equal(app.selectedGridSize.value, next);
  }
}
const beforeHash = app.selectedTopologyHash.value;
const beforeDefinition = app.selectedTopologyDefinition.value;
assert.equal(app.selectTopologyPreset('invalid-round3-preset'), null);
assert.equal(app.selectedTopologyHash.value, beforeHash);
assert.equal(app.selectedTopologyDefinition.value, beforeDefinition);
app.generateTopologyBoard();
assert.ok(app.selectedTopologyDefinition.value.generator, app.topologySetupMessage.value);
const board = compileBoard(app.selectedTopologyDefinition.value).value;
app.updateTopologyStarts({ mode: 'random', countPerPlayer: 2 });
const randomHash = app.selectedTopologyHash.value;
const randomRoots = compileBoard(app.selectedTopologyDefinition.value).value.startingRoots;
assert.equal(randomRoots.BLACK.length, 2);
assert.equal(randomRoots.WHITE.length, 2);
panel.setup({ language: 'en', draft: app.topologyDraft.value });
panel.setup({ language: 'en', draft: app.topologyDraft.value });
assert.equal(app.selectedTopologyHash.value, randomHash, 'rebuilding UI does not redraw random roots');
assert.deepEqual(compileBoard(app.selectedTopologyDefinition.value).value.startingRoots, randomRoots);
const { getGuideMarkdown } = await import('../GuideContent.js');
assert.match(getGuideMarkdown('rulesMath', 'zh'), /极点可以有多个真实方向/);
assert.match(getGuideMarkdown('rulesMath', 'en'), /A pole may have several actual sectors/);
console.log('PASS round3 topology slot, collapsed options, cone/sphere 5–15, resizing, rejected candidate and stable random roots');
